"""``make validation``: all frozen models on the validation window -> docs/results/validation.md."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from gridcast.backtest.dataset import truth
from gridcast.backtest.freeze import FROZEN_DIR, load_frozen
from gridcast.backtest.runner import load_backtest_config, run_validation
from gridcast.config import Settings
from gridcast.evaluate.metrics import Scores
from gridcast.evaluate.report import comparison_markdown, daily_losses


def build(data_dir: Path | None = None, out: Path = Path("docs/results/validation.md")) -> Path:
    data_dir = data_dir or Settings().data_dir
    cfg = load_backtest_config()
    da_ozp = pd.read_parquet(data_dir / "silver" / "da_ozp").drop(
        columns=["month"], errors="ignore"
    )
    actual = truth(da_ozp)
    scores: dict[str, Scores] = {}
    losses: dict[str, pd.DataFrame] = {}
    cache = data_dir / "gold" / "forecasts" / "validation"
    for path in sorted(FROZEN_DIR.glob("*.yaml")):
        frozen = load_frozen(path.stem)
        model = str(frozen["model"])
        label = f"{model}+cqr" if frozen.get("calibrate_cqr") else model
        result, s = run_validation(
            model,
            data_dir=data_dir,
            params={model: frozen.get("params") or {}},
            calibrate=bool(frozen.get("calibrate_cqr")),
            out_root=cache,
        )
        scores[label] = s
        losses[label] = daily_losses(result.forecasts, actual)
    window = f"{cfg.validation_eval.start} to {cfg.validation_eval.end}"
    note = (
        f"Validation window {window}, inside the pre-registered validation split."
        " **Not test results**: the test window (from 2025-11-01) stays sealed until G1"
        " (ADR-011). Generated by `make validation` from the configs in `configs/frozen/`."
    )
    text = comparison_markdown(scores, losses, title="Validation results", note=note)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    return out
